/**
 * Tech governance policy templates for Oblig.
 * Draft bodies map to APAC vendor / TRM / data / AI themes.
 * Not legal advice — customise and have counsel review before external use.
 */

export interface PolicyTemplate {
  id: string;
  title: string;
  type: string;
  desc: string;
  /** Full draft body used when generating a policy document */
  body: string;
}

function shell(opts: {
  purpose: string;
  scope?: string;
  roles: string;
  requirements: string;
  related?: string;
}): string {
  return [
    '1. Purpose',
    opts.purpose,
    '',
    '2. Scope',
    opts.scope ??
      'This policy applies to all employees, contractors, and third parties who design, operate, access, or support company systems, products, or customer data.',
    '',
    '3. Roles and responsibilities',
    opts.roles,
    '',
    '4. Requirements',
    opts.requirements,
    '',
    '5. Related frameworks (reference)',
    opts.related ??
      'Themes commonly tested under APAC technology and vendor risk expectations (e.g. MAS TRM and outsourcing-related instruments, BNM RMiT, and peer market guidance). Confirm the instruments that apply to your buyers and licence class.',
    '',
    '6. Exceptions',
    'Exceptions require written approval from the policy owner and must be time-bound, risk-assessed, and logged.',
    '',
    '7. Review',
    'This policy is reviewed at least annually, after a material incident, or when relevant regulatory guidance changes. Version history is retained with the document.',
    '',
    '—',
    'Draft generated by Oblig for internal editing. Not legal or regulatory advice.',
  ].join('\n');
}

