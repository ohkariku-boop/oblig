export function getPolicyTemplate(idOrTitle: string): PolicyTemplate | undefined {
  const q = idOrTitle.toLowerCase();
  return POLICY_TEMPLATES.find(
    t => t.id === idOrTitle || t.title.toLowerCase() === q || t.title.toLowerCase().includes(q),
  );
}
